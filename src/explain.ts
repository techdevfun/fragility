/**
 * `fragility explain` - how each signal is measured, its thresholds,
 * and its sources. Transparency is a feature: every number the tool
 * reports must be explainable in one screen.
 */

export const EXPLAIN: Record<string, string> = {
  tests: `Signal 1 - Test shallowness
  What it measures: whether the tests covering the CHANGED lines
  actually check anything. Counts assertions per test, tests that
  assert nothing, and weak matchers (toBeTruthy, toBeDefined,
  toBeFalsy, toBeNull, assert x is not None, bare "assert x").
  With --coverage <lcov> it also reports branch/line coverage of the
  CHANGED lines only - never the whole-repo percentage.
  Scoring: start 100. -40 if under 1 assertion/test. -25 if over half
  the assertions are weak (-10 if any are weak). -15 if any test
  asserts nothing. -10 if no edge-case test (name mentions error,
  edge, boundary, invalid, empty, fail, exception, reject, timeout,
  overflow). With coverage: -(1 - rate) * 30.
  Limits: regex-based counting, not a full AST - table-driven and
  dynamic tests may be under-counted. It counts what tests assert,
  not whether the assertions are correct.`,
  abstraction: `Signal 2 - Over-abstraction
  What it measures: how deep the changed TS/JS functions delegate.
  For every function containing an added line: call-chain depth
  (longest chain of calls to locally defined functions), parameter
  count, branch count (if/for/while/switch/case/catch/&&/||/ternary),
  function length.
  Thresholds (tunable in fragility.config.json): depth >= 4,
  params >= 5, branches >= 10, length > 80 lines. Each flagged
  function costs 15 points (max 45); max depth >= 6 costs 10 more.
  Limits: regex-based, not a full AST - unusual syntax can be
  misread. A flagged function is a prompt to look, not a verdict.`,
  comprehension: `Signal 3 - Comprehension debt
  What it measures: the share of changed lines nobody has re-touched
  since an AI-marked commit (git blame + commit-message markers such
  as "Co-Authored-By: Claude", "generated by", "copilot",
  "AI-assisted" - configurable in fragility.config.json), plus how
  many distinct authors touched these files in the last 90 days.
  Markers are matched against the FULL commit message (subject +
  body), so a Co-Authored-By: trailer in the body counts.
  Scoring: -(orphan ratio * 60); -15 when exactly one author touched
  the files in 90 days.
  Limits: this reads commit MESSAGES, not authorship. A commit
  without a marker may still be AI-written. The signal is "lines
  un-retouched since an AI-marked commit", never "lines AI wrote".`,
  review: `Signal 4 - Review bottleneck
  What it measures: (a) the diff size mapped to the SmartBear
  detection curve (analysis of 2,500 PRs): ~87% of defects caught
  under 100 lines, 78% at 100-300, 65% at 300-600, 42% at 600-1,000,
  28% above 1,000 lines; (b) lines merged per day over the last 30
  days from git log, against a 400 lines/day sustainable review
  capacity - a heuristic default for this tool, not a SmartBear
  figure (SmartBear's data is about defect detection by PR size,
  not daily review velocity).
  Scoring: the detection estimate is mapped 87 -> 100, 28 -> 0.
  Velocity over 400 lines/day costs 20; over 800 costs 35.
  Velocity is only measured for a git range audit. A diff file has no
  repo context, so the current directory's history is never used.
  Limits: the curve is population data, not a prediction for this
  PR. It is reported as an estimate, with the source named.`,
  score: `Composite - FRAGILITY SCORE
  The mean of the signals that ran (0-100, 100 = robust).
  ROBUST >= 80, WATCH 60-79, FRAGILE < 60. Exit 0 for ROBUST/WATCH,
  exit 1 for FRAGILE (or below --fail-under), exit 2 for input
  errors. Signals without git history are skipped and excluded from
  the mean; the report says which ones.`,
};

export function explainText(signal?: string): string {
  if (!signal) {
    return (
      "fragility measures four fragility modes of AI-written code:\n\n" +
      "  tests          shallow tests on the changed lines\n" +
      "  abstraction    over-complex / over-DRY code, hard to debug\n" +
      "  comprehension  lines nobody understands or re-touched\n" +
      "  review         PRs arriving faster than human review\n" +
      "  score          how the composite FRAGILITY SCORE is built\n\n" +
      "Run `fragility explain <signal>` for the measurement method,\n" +
      "thresholds, and sources of one signal."
    );
  }
  const key = signal.toLowerCase();
  if (key in EXPLAIN) return EXPLAIN[key];
  return `Unknown signal "${signal}". Known signals: tests, abstraction, comprehension, review, score.`;
}
