/**
 * Signal 3 - COMPREHENSION DEBT.
 *
 * Orphan ratio: the share of changed lines whose last-touching commit
 * (via git blame) carries an AI marker, meaning nobody has re-touched
 * those lines since an AI-marked commit. Markers are matched against
 * the FULL commit message (subject + body): the standard
 * `Co-Authored-By:` trailer lives in the body, never the subject, so
 * matching the subject alone silently misses real AI-marked commits.
 * This is a heuristic about commit messages, NOT proof of authorship: a commit without a marker
 * may still be AI-written, and a marker may be a false positive. The
 * tool reports "lines un-retouched since an AI-marked commit", never
 * "lines AI wrote".
 *
 * Knowledge concentration: distinct authors who touched the changed
 * files in the last 90 days. One author (or zero) means the change
 * lives in a single head.
 */
import { authorsForFiles, blameLines, logCommits } from "./git.js";

export const DEFAULT_MARKERS = [
  "co-authored-by: claude",
  "generated by",
  "copilot",
  "ai-assisted",
  "with claude",
  "with codex",
  "with copilot",
  "chatgpt",
  "gemini cli",
  "claude code",
  "ai-generated",
  "generated with ai",
];

/**
 * True when the FULL commit message (subject + body) contains any AI
 * marker. Substring match, case-insensitive, no word-boundary guard:
 * a bare mention of a tool name ("Reviewed Claude's comments") is
 * not a marker, but any sentence containing a marker phrase is.
 */
export function isAiMarked(message: string, markers: string[] = DEFAULT_MARKERS): boolean {
  const lower = message.toLowerCase();
  return markers.some((m) => lower.includes(m.toLowerCase()));
}

export interface ComprehensionResult {
  orphanLines: number;
  changedLines: number;
  orphanRatio: number; // 0..1
  authors90d: number;
  authorList: string[];
  skipped: boolean;
  skipReason?: string;
}

export function analyzeComprehension(
  repoDir: string,
  changedFiles: { path: string; lineNos: number[] }[],
  markers: string[] = DEFAULT_MARKERS,
): ComprehensionResult {
  const commits = logCommits(repoDir);
  if (commits.length === 0) {
    return {
      orphanLines: 0,
      changedLines: 0,
      orphanRatio: 0,
      authors90d: 0,
      authorList: [],
      skipped: true,
      skipReason: "no git history",
    };
  }
  const byHash = new Map(commits.map((c) => [c.hash, c]));
  let orphan = 0;
  let total = 0;
  let blameWorked = false;
  for (const f of changedFiles) {
    const blame = blameLines(repoDir, f.path, f.lineNos);
    if (blame === null) continue;
    if (blame.size > 0) blameWorked = true;
    for (const ln of f.lineNos) {
      total++;
      const hash = blame.get(ln);
      if (!hash) continue; // uncommitted / new file: not orphan, not human either
      const c = byHash.get(hash);
      if (c && isAiMarked(c.message, markers)) orphan++;
    }
  }
  if (!blameWorked) {
    return {
      orphanLines: 0,
      changedLines: 0,
      orphanRatio: 0,
      authors90d: 0,
      authorList: [],
      skipped: true,
      skipReason: "changed files have no git history",
    };
  }
  // Authors in the last 90 days touching the changed files (path-scoped).
  const authorList = authorsForFiles(
    repoDir,
    changedFiles.map((f) => f.path),
    90,
  );
  return {
    orphanLines: orphan,
    changedLines: total,
    orphanRatio: total === 0 ? 0 : orphan / total,
    authors90d: authorList.length,
    authorList,
    skipped: false,
  };
}
